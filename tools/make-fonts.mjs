/* Turns the woff2 files in fonts/ into src/fonts.css, with the faces inlined as
 * data URIs.
 *
 * The point is that index.html is genuinely self-contained: copy the one file to
 * a machine with no network and it looks and works exactly as it does online.
 * Linking a font from a CDN also meant every launch, including a solo game,
 * handed a third party the player's IP address.
 *
 * Both families are variable fonts, so one file per family covers every weight
 * the interface uses. Re-run this after replacing a woff2 and commit the result.
 */
import { readFileSync, writeFileSync } from "node:fs";

const FACES = [
  { file: "fonts/archivo-latin.woff2", family: "Archivo", range: "100 900" },
  { file: "fonts/fredoka-latin.woff2", family: "Fredoka", range: "300 700" }
];

/* The built page is meant to be copied around on its own, so the licence notice
   has to travel inside it. The OFL explicitly allows the notice to live in a
   human-readable header like this one. */
const parts = [
  "/* Embedded typefaces -- GENERATED by tools/make-fonts.mjs, do not edit.",
  " *",
  " * Archivo  (c) The Archivo Project Authors, Omnibus-Type",
  " * Fredoka  (c) The Fredoka Project Authors, Milena Brandao / Hafontia",
  " *",
  " * Both are licensed under the SIL Open Font License, Version 1.1.",
  " * You may use, embed and redistribute them under that licence; they may not",
  " * be sold on their own. Full text: https://openfontlicense.org",
  " * A copy also ships in the repository at fonts/OFL.txt.",
  " */"
];

for(const face of FACES){
  const bytes = readFileSync(face.file);
  if(bytes.slice(0, 4).toString("hex") !== "774f4632"){
    throw new Error(`${face.file} is not a woff2 file`);
  }
  parts.push(
    "@font-face{",
    `  font-family:"${face.family}";`,
    "  font-style:normal;",
    `  font-weight:${face.range};`,
    "  font-display:swap;",
    `  src:url(data:font/woff2;base64,${bytes.toString("base64")}) format("woff2");`,
    "}"
  );
  console.log(`${face.family}: ${bytes.length} bytes -> ${Math.round(bytes.length * 4 / 3 / 1024)}KB inlined`);
}

writeFileSync("src/fonts.css", parts.join("\n") + "\n");
console.log("wrote src/fonts.css");
