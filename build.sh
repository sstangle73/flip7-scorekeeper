#!/bin/sh
# src/{game,net,app}.js + src/page.html  ->  app.html  ->  index.html
# and an ESM copy of the rules core for the Cloudflare Worker.
set -e

# app.html: the Artifact-ready fragment
{
  cat src/page.html
  printf '%s\n' '<script>'
  cat src/game.js
  cat src/net.js
  cat src/app.js
  printf '%s\n' '</script>'
} > app.html

# index.html: the same thing as a standalone page
{
  printf '%s\n' '<!doctype html>'
  printf '%s\n' '<html lang="en">'
  printf '%s\n' '<head>'
  printf '%s\n' '<meta charset="utf-8">'
  printf '%s\n' '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">'
  printf '%s\n' '<meta name="color-scheme" content="light dark">'
  printf '%s\n' '<meta name="description" content="Tap the cards in front of each player and score a round of Flip 7.">'
  cat app.html
  printf '%s\n' '</body>'
  printf '%s\n' '</html>'
} > index.html

# server/src/rules.js: same rules core, as an ES module. Generated -- never edit.
{
  printf '%s\n' '/* GENERATED by build.sh from src/game.js -- do not edit. */'
  cat src/game.js
  printf '%s\n' 'export default Flip7Rules;'
  printf '%s\n' 'export { Flip7Rules };'
} > server/src/rules.js

echo "built app.html, index.html, server/src/rules.js"
