#!/bin/sh
# src/{qr,game,view,stats,net,app}.js + src/page.html  ->  app.html  ->  index.html
# and an ESM copy of the rules core for the Cloudflare Worker.
set -e

# The relay baked into this build: $RELAY_URL wins, else the first non-comment
# line of relay.config, else empty (standalone only).
RELAY="${RELAY_URL:-}"
if [ -z "$RELAY" ] && [ -f relay.config ]; then
  RELAY=$(grep -v '^[[:space:]]*#' relay.config | grep -v '^[[:space:]]*$' | head -1 | tr -d '[:space:]')
fi
case "$RELAY" in
  ""|https://*|http://*) ;;
  *) echo "relay.config must hold an http(s) URL, got: $RELAY" >&2; exit 1 ;;
esac

# Substitute it into the RELAY_URL line as the sources are concatenated.
bake() { sed "s|^  var RELAY_URL = \"\";|  var RELAY_URL = \"$RELAY\";|" "$1"; }

# The embedded faces replace the <!--FONTS--> marker, so the page carries its own
# typography and needs nothing from the network.
if [ ! -f src/fonts.css ]; then
  echo "src/fonts.css is missing -- run: node tools/make-fonts.mjs" >&2; exit 1
fi
{
  echo '<style>'
  cat src/fonts.css
  echo '</style>'
} > .fonts.block

# app.html: the Artifact-ready fragment (no <head>, so no PWA tags here)
{
  awk '/<!--FONTS-->/{while((getline line < ".fonts.block")>0) print line; close(".fonts.block"); found=1; next} {print} END{if(!found){print "the <!--FONTS--> marker was not found in src/page.html" > "/dev/stderr"; exit 1}}' src/page.html
  echo '<script>'
  cat src/qr.js
  cat src/game.js
  cat src/view.js
  cat src/stats.js
  cat src/net.js
  bake src/app.js
  echo '</script>'
} > app.html

# index.html: the same thing as a standalone, installable page
{
  echo '<!doctype html>'
  echo '<html lang="en">'
  echo '<head>'
  echo '<meta charset="utf-8">'
  echo '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">'
  echo '<meta name="color-scheme" content="light dark">'
  echo '<meta name="description" content="Tap the cards in front of each player and score a round of Flip 7.">'
  echo '<link rel="manifest" href="manifest.webmanifest">'
  echo '<meta name="theme-color" content="#0D1729">'
  echo '<meta name="mobile-web-app-capable" content="yes">'
  echo '<meta name="apple-mobile-web-app-capable" content="yes">'
  echo '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">'
  echo '<meta name="apple-mobile-web-app-title" content="Flip 7">'
  echo '<link rel="apple-touch-icon" href="icon-180.png">'
  echo '<link rel="icon" href="icon-192.png">'
  cat app.html
  echo '</body>'
  echo '</html>'
} > index.html

# sw.js carries a stamp derived from the built page. Any content change gives the
# service worker new bytes, which is the only thing that makes a browser reinstall
# it and refresh the cached shell.
# Strip CRs first: a Windows working copy and a Linux CI runner would otherwise
# hash the same content differently and disagree about the stamp.
STAMP=$( { tr -d '\r' < index.html; cat manifest.webmanifest icon-180.png icon-192.png icon-512.png; } | cksum | cut -d' ' -f1)
sed "s/^const BUILD = \".*\";/const BUILD = \"$STAMP\";/" sw.js > sw.js.tmp && mv sw.js.tmp sw.js

# server/src/rules.js: same rules core, as an ES module. Generated -- never edit.
{
  echo '/* GENERATED by build.sh from src/game.js -- do not edit. */'
  cat src/game.js
  echo 'export default Flip7Rules;'
  echo 'export { Flip7Rules };'
} > server/src/rules.js

rm -f .fonts.block
echo "built app.html, index.html, server/src/rules.js"
